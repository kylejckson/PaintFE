impl MenuCommand {
    pub const ALL: &'static [Self] = &[
        Self::FileInfo,
        Self::FileDuplicate,
        Self::FilePrint,
        Self::FileQuit,
        Self::EditPasteAsLayer,
        Self::EditInvertSelection,
        Self::SelectColorRange,
        Self::EditSelectContentBounds,
        Self::EditPreferences,
        Self::CanvasCropToSelection,
        Self::CanvasNewTextLayer,
        Self::CanvasFlipHorizontal,
        Self::CanvasFlipVertical,
        Self::CanvasRotate90Cw,
        Self::CanvasRotate90Ccw,
        Self::CanvasRotate180,
        Self::ColorColorToAlpha,
        Self::ColorRecoverTransparency,
        Self::FilterStylizeCanvasBorder,
        Self::FilterStylizeSeamless,
        Self::FileClearRecent,
        Self::CanvasStraighten,
        Self::ViewTools,
        Self::ViewLayers,
        Self::ViewHistory,
        Self::ViewColors,
        Self::ViewPalette,
        Self::ViewScriptEditor,
        Self::ViewPixelGrid,
        Self::ViewCmyk,
        Self::ViewLight,
        Self::ViewDark,
        Self::HelpQuickStart,
        Self::HelpAiSetup,
        Self::HelpDocumentation,
        Self::CanvasAlign,
        Self::ToolEllipseSelect,
        Self::ToolMoveSelection,
        Self::ToolContentAwareBrush,
        Self::ToolLiquify,
        Self::ToolSmudge,
        Self::ToolPerspectiveCrop,
        Self::GuidesRulers,
        Self::GuidesVisible,
        Self::GuidesLocked,
        Self::GuidesSnap,
        Self::GuidesNew,
        Self::GuidesClear,
    ];
    pub fn from_config_name(name: &str) -> Option<Self> {
        Self::ALL
            .iter()
            .copied()
            .find(|action| format!("Menu({action:?})") == name)
    }
    pub fn label(self) -> String {
        crate::i18n::translate(command_spec(BindableAction::Menu(self)).unwrap().label_key)
    }
    pub fn category(self) -> String {
        crate::i18n::translate(
            command_spec(BindableAction::Menu(self))
                .unwrap()
                .category_key,
        )
    }
}
